const pages = Array.from(document.querySelectorAll(".page"));
const tabs = Array.from(document.querySelectorAll("[data-page]"));
const previous = document.querySelector("#previous");
const next = document.querySelector("#next");
const language = document.querySelector("#language");
const journey = document.querySelector("#journey");
let currentPage = 0;
let touchStart = null;

function showPage(index) {
  currentPage = Math.max(0, Math.min(pages.length - 1, index));
  pages.forEach((page, i) => { page.hidden = i !== currentPage; });
  tabs.forEach((tab, i) => tab.setAttribute("aria-pressed", String(i === currentPage)));
  previous.disabled = currentPage === 0;
  next.disabled = currentPage === pages.length - 1;
}

function setLanguage(locale) {
  const text = translations[locale] || translations.en;
  document.documentElement.lang = translations[locale] ? locale : "en";
  language.value = document.documentElement.lang;
  document.querySelectorAll("[data-i18n]").forEach(element => {
    element.textContent = text[element.dataset.i18n];
  });
  document.querySelectorAll("[data-i18n-aria]").forEach(element => {
    element.setAttribute("aria-label", text[element.dataset.i18nAria]);
  });
}

tabs.forEach(tab => tab.addEventListener("click", () => showPage(Number(tab.dataset.page))));
previous.addEventListener("click", () => showPage(currentPage - 1));
next.addEventListener("click", () => showPage(currentPage + 1));
language.addEventListener("change", () => setLanguage(language.value));
document.addEventListener("keydown", event => {
  if (event.altKey || event.ctrlKey || event.metaKey || (event.target instanceof Element && event.target.closest("select, input, textarea, [contenteditable]"))) return;
  if (event.key === "ArrowLeft") showPage(currentPage - 1);
  if (event.key === "ArrowRight") showPage(currentPage + 1);
});
journey.addEventListener("touchstart", event => {
  touchStart = event.touches.length === 1 ? { x: event.touches[0].clientX, y: event.touches[0].clientY } : null;
}, { passive: true });
journey.addEventListener("touchend", event => {
  if (!touchStart || event.changedTouches.length !== 1 || event.touches.length) {
    touchStart = null;
    return;
  }
  const dx = event.changedTouches[0].clientX - touchStart.x;
  const dy = event.changedTouches[0].clientY - touchStart.y;
  if (Math.abs(dx) > 60 && Math.abs(dx) > Math.abs(dy)) showPage(currentPage + (dx < 0 ? 1 : -1));
  touchStart = null;
}, { passive: true });
journey.addEventListener("touchcancel", () => { touchStart = null; });

setLanguage((navigator.language || "en").split("-")[0].toLowerCase());
showPage(0);
document.querySelector(".language").hidden = false;
document.querySelector(".tabs").hidden = false;
document.querySelector(".page-controls").hidden = false;
